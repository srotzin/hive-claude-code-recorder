// Builds the vendor copies, the licence statement, and tamper cases for the four vendor surfaces from
// real sessions, and checks every one against what the live witness remembers. Nothing is sent to the witness.
//   node tests/vendor-tamper.mjs <example dir> <recorder keys dir> <vendor key pem> <from> <to> [witness url]
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { canon, body, digestOf, discloseFor, stubOf, verifyRecord, checkAnswer, statementBody, checkStatement } from "../plugins/hive-recorder/scripts/core.mjs";
import { c, fetchMemory, fetchSessions } from "../plugins/hive-recorder/scripts/verify.mjs";
import { ml_dsa65 } from "../plugins/hive-recorder/scripts/vendor/ml-dsa-65.mjs";

const [E, keys, vpem, from, to, wurl = "https://witness.thehiveryiq.com"] = process.argv.slice(2);
const WKEY = "FCHk4lQ-PvNo2cxkUoL0VlGuKdU6DiK-vPraAR7gyHE";
const jl = f => fs.readFileSync(f, "utf8").split("\n").filter(Boolean).map(l => JSON.parse(l));
const wr = (f, L) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, L.map(x => JSON.stringify(x)).join("\n") + "\n"); };
const L1 = jl(path.join(E, "session-1.jsonl")), L2 = jl(path.join(E, "session-2.jsonl"));
const ANSWER = fs.readFileSync(path.join(E, "answer-1.txt"), "utf8");
const sk = crypto.createPrivateKey(fs.readFileSync(path.join(keys, "recorder-ed25519.pem")));
const pq = ml_dsa65.keygen(Uint8Array.from(Buffer.from(fs.readFileSync(path.join(keys, "recorder-ml-dsa-65.seed"), "utf8").trim(), "hex")));
const vk = crypto.createPrivateKey(fs.readFileSync(vpem)), vpub = crypto.createPublicKey(vk).export({ format: "jwk" }).x;
const pub = L1[0].public_key, H = c.sha256hex, MD = "market-data", RD = "ref-data";
// Re-sign a whole record with both of the recorder's own keys.
function rebuild(lines) {
  let prev = "0".repeat(64);
  return lines.map((l0, i) => {
    const l = { ...body(l0), seq: i, prev };
    if (l.event === "Seal") { l.count = i; l.head = prev; }
    const cc = l.form === "split" ? canon(digestOf(l, H)) : canon(l), h = H(cc); prev = h;
    return { ...l, hash: h, sig: crypto.sign(null, Buffer.from(cc), sk).toString("base64url"), sig_pq: Buffer.from(ml_dsa65.sign(Buffer.from(cc), pq.secretKey)).toString("base64url") };
  });
}
const signSt = b => ({ ...b, sig: crypto.sign(null, Buffer.from(canon(b)), sk).toString("base64url") });
const accept = st => { const { accepted, ...x } = st; const a = { accepted_at: new Date().toISOString() }; return { ...x, accepted: { vendor_key: vpub, ...a, sig: crypto.sign(null, Buffer.from(canon({ statement_sha256: H(canon(x)), ...a })), vk).toString("base64url") } }; };
const period = { from: new Date(from).toISOString(), to: new Date(to).toISOString() };
const mkSt = discs => signSt({ ...statementBody(discs, MD, period, c), issued_at: new Date().toISOString() });

// Genuine artifacts
const A1 = discloseFor(L1, MD, H), A2 = discloseFor(L2, MD, H), B1 = discloseFor(L1, RD, H), B2 = discloseFor(L2, RD, H);
wr(path.join(E, "copies/session-1.market-data.jsonl"), A1); wr(path.join(E, "copies/session-2.market-data.jsonl"), A2);
wr(path.join(E, "copies/session-1.ref-data.jsonl"), B1); wr(path.join(E, "copies/session-2.ref-data.jsonl"), B2);
const ST = accept(mkSt([A1, A2]));
fs.writeFileSync(path.join(E, "copies/statement.market-data.json"), JSON.stringify(ST, null, 1));
fs.writeFileSync(path.join(E, "copies/vendor-key.market-data.json"), JSON.stringify({ vendor: MD, alg: "Ed25519", public_key: vpub, note: "Stand-in vendor key, generated by Hive for this demo. In use, the vendor holds its own key." }, null, 1));

const iMort = L1.findIndex(l => l.event === "PreToolUse" && l.scope && l.scope.outside.datasets && l.scope.outside.datasets.length);
const mortId = L1[iMort].tool.use_id;
const iBrentPost = L1.findIndex(l => l.event === "PostToolUse" && l.tool && l.tool.name === "mcp__market-data__get_eod");
const iMortPost = L1.findIndex(l => l.event === "PostToolUse" && l.tool && l.tool.use_id === mortId);
const iStop = L1.findIndex(l => l.event === "Stop");
const iRefPre = L1.findIndex(l => l.event === "PreToolUse" && l.vendor === RD);
const issuerId = L1[iRefPre].tool.use_id;
const relabel = rebuild(L1.map(l => l.tool && l.tool.use_id === mortId ? { ...l, vendor: RD } : l));
const noIssuer = rebuild(L1.filter(l => !(l.tool && l.tool.use_id === issuerId)).map(l => l.answer ? { ...l, answer: { ...l.answer, drew_on: l.answer.drew_on.filter(d => d.vendor !== RD) } } : l));
const noMort = rebuild(L1.filter(l => !(l.tool && l.tool.use_id === mortId)).map(l => l.answer ? { ...l, answer: { ...l.answer, drew_on: l.answer.drew_on.filter(d => d.seq !== iMortPost) } } : l));
const trailCut = rebuild(L1.map((l, i) => i === iStop ? { ...l, answer: { ...l.answer, drew_on: l.answer.drew_on.filter(d => d.seq !== iMortPost) } } : l));
const trailMoved = rebuild(L1.map((l, i) => i === iStop ? { ...l, answer: { ...l.answer, drew_on: l.answer.drew_on.map(d => d.seq === iMortPost ? { ...d, seq: iBrentPost } : d) } } : l));
const lowered = (() => { const { sig, accepted, ...b } = ST; return signSt({ ...b, usage: b.usage.map(u => ({ ...u, outside: 0 })), outside: [] }); })();
const reissued = (() => { const { sig, accepted, ...b } = ST; return { ...signSt({ ...b, issued_at: new Date(Date.now() + 1000).toISOString() }), accepted: ST.accepted }; })();
const sMort = discloseFor(noMort, MD, H);

const cases = [
  // group, id, what, kind, vendor, files (record copies), expected
  ["copy", "pull-hidden", "In market-data's copy, the mortgage pull is hidden as digest only.", "record", MD, { "c.jsonl": A1.map((l, i) => i === iMort ? stubOf(L1[i], H) : l) }, "DISCLOSURE"],
  ["copy", "stub-relabelled", "The mortgage pull is hidden, and its digest-only line is relabelled as a ref-data line so the hiding looks allowed.", "record", MD, { "c.jsonl": A1.map((l, i) => i === iMort ? { ...stubOf(L1[i], H), vendor: RD } : l) }, "ENTRY_HASH"],
  ["copy", "stub-dropped", "One of the hidden ref-data lines is taken out of the copy altogether.", "record", MD, { "c.jsonl": A1.filter((l, i) => i !== iRefPre) }, "CHAIN_ORDER"],
  ["copy", "relabelled-resigned", "The mortgage pull is relabelled as ref-data in the record itself and every line re-signed with both recorder keys, then hidden from market-data.", "record", MD, { "c.jsonl": discloseFor(relabel, MD, H) }, "WITNESS"],
  ["vendors", "wrong-copy", "ref-data's copy, which hides every market-data line, is handed to market-data as if it were its copy.", "record", MD, { "c.jsonl": B1 }, "DISCLOSURE"],
  ["vendors", "entitlement-hidden", "market-data's copy hides market-data's own entitlement line, so nobody can see what it was entitled to.", "record", MD, { "c.jsonl": A1.map((l, i) => i === 2 ? stubOf(L1[i], H) : l) }, "DISCLOSURE"],
  ["vendors", "issuer-pull-deleted", "ref-data's issuer pull is deleted, the record re-signed with both recorder keys, and ref-data handed a copy of that.", "record", RD, { "c.jsonl": discloseFor(noIssuer, RD, H) }, "WITNESS"],
  ["answer", "figure-changed", "The answer is handed over with Brent's 84.12 changed to 82.40.", "answer", MD, { "c.jsonl": A1 }, "ANSWER", ANSWER.replace("84.12", "82.40")],
  ["answer", "trail-cut", "The answer's link to the mortgage pull is removed from the trail and every line re-signed.", "answer", MD, { "c.jsonl": discloseFor(trailCut, MD, H) }, "WITNESS", ANSWER],
  ["answer", "trail-moved", "The answer's link to the mortgage pull is pointed at the Brent pull instead, so the answer seems to use only allowed data, and every line re-signed.", "answer", MD, { "c.jsonl": discloseFor(trailMoved, MD, H) }, "WITNESS", ANSWER],
  ["statement", "outside-dropped", "The statement is re-signed with the mortgage pull taken out, so market-data sees zero pulls outside its entitlement.", "statement", MD, { "s1.jsonl": A1, "s2.jsonl": A2, "statement.json": lowered }, "USAGE"],
  ["statement", "session-left-out", "The statement covers only the second session, and is re-signed.", "statement", MD, { "s2.jsonl": A2, "statement.json": mkSt([A2]) }, "COMPLETE"],
  ["statement", "record-rebuilt", "The mortgage pull is deleted from the record, every line re-signed, and the copies and statement rebuilt to match.", "statement", MD, { "s1.jsonl": sMort, "s2.jsonl": A2, "statement.json": mkSt([sMort, A2]) }, "RECORD"],
  ["statement", "acceptance-moved", "market-data's acceptance is moved onto a reissued statement it never accepted.", "statement", MD, { "s1.jsonl": A1, "s2.jsonl": A2, "statement.json": reissued }, "ACCEPTED"],
];

const memo = {};
for (const L of [L1, L2]) memo[H(String(L[0].session))] = (await fetchMemory(L, wurl)).statements;
const sessions = await fetchSessions(pub, period, wurl);
fs.writeFileSync(path.join(E, "copies/witness-sessions.json"), JSON.stringify({ from: wurl, period, sessions }, null, 1));
const recOpts = (L, vendor) => ({ pin: pub, witnessPin: WKEY, allowRedacted: true, discloseFor: vendor, memory: { statements: memo[H(String(L[0].session))] || [] }, requireMemory: true });
export function judge(cs, files) { return null; }
const T = path.join(E, "tamper"); fs.mkdirSync(T, { recursive: true });
const man = []; let n = 0;
// Genuine checks first
const g = [
  ["market-data copy, session 1", verifyRecord(A1, c, recOpts(A1, MD)).ok],
  ["ref-data copy, session 1", verifyRecord(B1, c, recOpts(B1, RD)).ok],
  ["answer trail", checkAnswer(A1, ANSWER, c).ok],
  ["statement", checkStatement(ST, [A1, A2], c, { recorderPin: pub, vendorPin: vpub, witnessPin: WKEY, memory: memo, witnessSessions: sessions }).ok],
];
for (const [k, ok] of g) console.log((ok ? "ok   genuine " : "FAIL genuine ") + k);
for (const [group, id, what, kind, vendor, files, expected, text] of cases) {
  const out = {};
  for (const [f, v] of Object.entries(files)) { const p = id + "." + f; out[f] = p; if (f.endsWith(".json")) fs.writeFileSync(path.join(T, p), JSON.stringify(v, null, 1)); else wr(path.join(T, p), v); }
  if (text !== undefined) { fs.writeFileSync(path.join(T, id + ".answer.txt"), text); out.answer = id + ".answer.txt"; }
  let got, why;
  if (kind === "record" || kind === "answer") {
    const L = files["c.jsonl"], r = verifyRecord(L, c, recOpts(L, vendor));
    if (!r.ok) { got = r.first_failure.gate; why = r.first_failure.why; }
    else if (kind === "answer") { const a = checkAnswer(L, text, c); if (!a.ok) { got = "ANSWER"; why = a.why; } }
  } else {
    const discs = Object.entries(files).filter(([f]) => f.endsWith(".jsonl")).map(([, v]) => v);
    const r = checkStatement(files["statement.json"], discs, c, { recorderPin: pub, vendorPin: vpub, witnessPin: WKEY, memory: memo, witnessSessions: sessions });
    if (!r.ok) { got = r.step; why = r.why; }
  }
  const ok = got === expected; if (ok) n++;
  man.push({ group, id, what, kind, vendor, files: out, expected, got: got || null, why: why || null });
  console.log((ok ? "ok   " : "FAIL ") + group + "/" + id + "  " + (got || "accepted") + (why ? ", " + why : ""));
}
fs.writeFileSync(path.join(T, "MANIFEST.json"), JSON.stringify(man, null, 1));
console.log(`\n${n} of ${cases.length} rejected at the expected step.`);
process.exitCode = n === cases.length && g.every(x => x[1]) ? 0 : 1;
